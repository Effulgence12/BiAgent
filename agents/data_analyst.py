        "weight_freight",
        "SELECT weight_bucket, delivery_status, order_count, avg_weight_g, avg_volume_cm3, avg_freight, avg_price FROM mv_weight_freight ORDER BY avg_weight_g, delivery_status LIMIT 40",
        "商品重量/体积与运费关系",
